export function buildProgress() {
  const counts = {};
  for (const s of stages) for (const i of s.items) counts[i.status] = (counts[i.status] || 0) + 1;
  return {
    generatedAt: new Date().toISOString(),
    statuses: { BV, P, F, N },
    counts,
    stages,
    note: 'BUILT AND VERIFIED means the item exists, matches this specification, and its check was run in this app. PARTIAL lists the missing part and the exact next step.',
  };
}
